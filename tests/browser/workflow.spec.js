import {test,expect} from '@playwright/test';

test('dashboard connects quotation, job checklist, partial payment and delivery',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.request.post('/api/login',{data:{email:'admin@example.test',password:'browser-admin-password-2026',role:'admin'}});
 const response=await page.request.post('/api/documents',{data:{type:'quotation',customer:'Connected Driver',phone:'9876543210',vehicle:'Test hatchback',items:[{id:'ceramic',quantity:1,price:100}],discount:0,gstRate:18}});
 expect(response.ok()).toBeTruthy();
 await page.goto('/');await page.locator('#admin-nav').click();
 await page.getByRole('button',{name:'Quotations',exact:true}).click();
 await page.locator('.record').filter({hasText:'Connected Driver'}).getByRole('button',{name:'Schedule job'}).click();
 await page.locator('#schedule-form [name=assignee]').fill('Detailing team');
 await page.locator('#schedule-form [name=accepted]').check();
 await page.getByRole('button',{name:'Approve & schedule',exact:true}).click();
 await expect(page.locator('#job-dialog')).toBeVisible();
 await expect(page.locator('#job-title')).toHaveText('Connected Driver');
 await page.getByRole('button',{name:'Start work',exact:true}).click();
 await expect(page.locator('.job-timeline [aria-current]')).toHaveText('In progress');
 await page.getByRole('button',{name:'Send to quality check',exact:true}).click();
 await expect(page.locator('#job-error')).toContainText('Complete the service checklist');
 await page.locator('#job-form [data-check]').check();
 await page.getByRole('button',{name:'Send to quality check',exact:true}).click();
 await expect(page.locator('.job-timeline [aria-current]')).toHaveText('Quality check');
 await page.getByRole('button',{name:'Pass quality check',exact:true}).click();
 await page.getByRole('button',{name:'Generate bill',exact:true}).click();
 await expect(page.locator('#saved-document')).toContainText('Connected Driver');
 await page.locator('#view-dialog [data-close]').click();
 await page.locator('#job-dialog').getByRole('button',{name:'Record payment',exact:true}).click();
 await page.locator('#payment-form [name=amount]').fill('50');
 await page.locator('#payment-form [name=reference]').fill('UPI-123');
 await page.getByRole('button',{name:'Save payment',exact:true}).click();
 await expect(page.locator('#payment-summary')).toContainText('Partially paid');
 await expect(page.locator('#payment-history')).toContainText('UPI-123');
 await expect(page.locator('#payment-form [name=amount]')).toHaveValue('68');
 await page.locator('#payment-dialog [data-close]').click();
 await page.getByRole('button',{name:'Confirm delivery',exact:true}).click();
 await expect(page.locator('#job-error')).toContainText('settle its balance');
 await page.locator('#job-dialog').getByRole('button',{name:'Record payment',exact:true}).click();
 await page.getByRole('button',{name:'Save payment',exact:true}).click();
 await expect(page.locator('#payment-summary .status')).toHaveText('Paid');
 await page.locator('#payment-dialog [data-close]').click();
 await page.getByRole('button',{name:'Confirm delivery',exact:true}).click();
 await expect(page.locator('.job-timeline [aria-current]')).toHaveText('Delivered');
 await page.screenshot({path:'test-results/connected-job.png'});
 await page.locator('#job-dialog [data-close]').click();
 await page.getByRole('button',{name:'Today',exact:true}).click();
 await expect(page.locator('.workflow-metrics')).toContainText('Outstanding balance');
 await page.setViewportSize({width:390,height:844});
 await expect(page.locator('.workflow-metrics')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:'test-results/workflow-mobile.png',fullPage:true});
 expect(errors).toEqual([]);
});
